// Production-component rendering with synthetic fixtures only. Optional Playwright tooling.
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const requireTool = process.env.LR_BROWSER_TOOLS ? createRequire(path.join(process.env.LR_BROWSER_TOOLS, 'package.json')) : require;
const { chromium } = requireTool('playwright');
const esbuild = require(require.resolve('esbuild', { paths: [fs.realpathSync(path.join(root, 'node_modules/vite'))] }));
const out = process.env.LR_AGENT_UI_OUT || path.join(root, 'output/canvas-agent-r7-ui');
const checks = [];
(async () => {
  fs.mkdirSync(out, { recursive: true });
  await esbuild.build({ jsx: 'automatic', entryPoints: [path.join(__dirname, 'canvasAgentR7Ui.fixture.tsx')], bundle: true, outfile: path.join(out, 'fixture.js'), loader: { '.css': 'css' } });
  const html = `<!doctype html><html data-theme="dark"><meta charset="UTF-8"><link rel="stylesheet" href="/fixture.css"><style>html,body,#root{margin:0;width:100%;height:100%;font-family:Arial,'Noto Sans CJK SC',sans-serif;background:var(--theme-app-bg);color:var(--text-primary)}*{box-sizing:border-box}.fixture-stage{position:relative;width:100%;height:100%;background:radial-gradient(#343540 1px,transparent 1px) 0 0/22px 22px}.fixture-stage nav{position:absolute;left:20px;right:20px;top:16px;display:flex;flex-wrap:wrap;gap:6px}.fixture-stage nav button{font-size:11px;padding:6px;background:#202127;border:1px solid #454650;border-radius:8px;color:#ddd}.fixture-art{position:absolute;left:12%;top:30%;font-size:24px;color:#b1b8c7}.fixture-art small{font-size:13px;color:#717989}.canvas-r1-agent-panel{top:76px;}.canvas-agent-history-popover{background:var(--canvas-panel-surface)}</style><div id="root"></div><script src="/fixture.js"></script></html>`;
  const server = http.createServer((req, res) => { if(req.url==='/favicon.ico'){res.statusCode=204;res.end();return;} const name = req.url === '/' ? null : path.basename(req.url); if (!name) { res.setHeader('Content-Type','text/html'); res.end(html); } else if (['fixture.js','fixture.css'].includes(name)) { res.setHeader('Content-Type',name.endsWith('.js')?'text/javascript':'text/css'); res.end(fs.readFileSync(path.join(out,name))); } else { res.statusCode=404;res.end(); } });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser, context, page;
  const errors = [], unexpectedRequests = []; let failure;
  try {
  browser = await chromium.launch({ headless: true, ...(process.env.LR_CHROMIUM ? {executablePath:process.env.LR_CHROMIUM} : {}) });
    context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
    await context.route('**/*', route => {
      const url = new URL(route.request().url());
      if ((url.hostname === '127.0.0.1' && url.port === String(server.address().port)) || ['data:','blob:'].includes(url.protocol)) return route.continue();
      unexpectedRequests.push(url.origin); return route.abort();
    });
    await context.tracing.start({ screenshots:true, snapshots:true, sources:false });
    page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if(message.type()==='error') errors.push(message.text()); });
    await page.goto(`http://127.0.0.1:${server.address().port}/`);
    await page.locator('.canvas-agent-turn').waitFor();
    const settleFinite = locator => locator.evaluate(async el=>{await Promise.all(el.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{})));});
    const historicalMark = page.locator('.canvas-agent-turn-mark .canvas-agent-orb-black-hole').first();
    assert.deepEqual(await historicalMark.evaluate(el => ({width:getComputedStyle(el).width,height:getComputedStyle(el).height})), {width:'88px',height:'64px'});
    assert.ok((await historicalMark.boundingBox()).width > 30, 'historical mark must not inherit the old 14px generic SVG rule');
    checks.push('historical shared black hole keeps its scoped dimensions');
    const userBubble = await page.locator('.canvas-agent-user-bubble').first().boundingBox();
    const firstTurnMark = await page.locator('.canvas-agent-turn-mark').first().boundingBox();
    assert.ok(firstTurnMark.y-userBubble.y-userBubble.height >= 16 && firstTurnMark.y-userBubble.y-userBubble.height <= 32,'user-to-Agent spacing is compact without reserving a whole actions row');

    await page.mouse.move(10, 890);
    const actions = page.locator('.canvas-agent-turn .canvas-agent-message-actions').last();
    await settleFinite(actions);
    assert.equal(await actions.evaluate(el => getComputedStyle(el).opacity), '0');
    await page.locator('.canvas-agent-turn').hover();
    await settleFinite(actions);
    assert.equal(await actions.evaluate(el => getComputedStyle(el).opacity), '1');
    assert.equal(await actions.locator('button').allTextContents().then(values => values.every(value => !value)), true);
    checks.push('assistant icon actions are hidden at rest and revealed on hover');
    const userActions = page.locator('.canvas-r1-agent-message.is-user > .canvas-agent-message-actions').first();
    await page.locator('.canvas-agent-user-bubble').first().hover();
    await userActions.locator('button').first().hover();
    await settleFinite(userActions);
    assert.equal(await userActions.evaluate(el=>getComputedStyle(el).opacity),'1');
    assert.equal((await page.locator('.canvas-agent-turn-mark').first().boundingBox()).y,firstTurnMark.y,'hover actions do not shift the next turn');
    checks.push('user actions stay reachable outside the bubble without a reserved blank row');

    assert.equal(await page.locator('.canvas-agent-user-bubble .canvas-agent-message-actions').count(), 0);
    checks.push('user actions are outside message bubble');
    await page.mouse.move(10, 890);
    await Promise.all([settleFinite(actions),settleFinite(userActions)]);
    assert.equal(await userActions.evaluate(el=>getComputedStyle(el).opacity),'0');
    await page.screenshot({ path: path.join(out, 'conversation-1440.png') });
    await page.locator('.canvas-agent-turn-process > summary').click();
    await page.screenshot({ path: path.join(out, 'activity-expanded-1440.png') });
    const model = await page.locator('.canvas-agent-model-trigger').boundingBox();
    const strength = await page.locator('.canvas-agent-strength').boundingBox();
    assert.ok(model && strength && strength.x - (model.x+model.width) < 12,'model stays adjacent to reasoning strength');
    await page.getByRole('button', { name: '旧版九段', exact: true }).click();
    assert.equal(await page.locator('.canvas-agent-turn').count(), 1);
    await page.screenshot({ path: path.join(out, 'legacy-nine-fragments.png') });
    checks.push('legacy nine assistant fragments render as one turn');
    await page.getByRole('button', { name: '完整对话', exact: true }).click();
    const composerBefore = await page.locator('.canvas-r1-agent-composer').boundingBox();
    await page.locator('.canvas-agent-run-settings > summary').click();
    const composerAfter = await page.locator('.canvas-r1-agent-composer').boundingBox();
    assert.ok(Math.abs(composerBefore.height - composerAfter.height) < 1);
    for(let i=0;i<100;i++) await page.locator('.canvas-agent-generation-permission input').click();
    assert.equal(await page.locator('.canvas-agent-recovery').count(),0);
    await page.locator('.canvas-agent-generation-permission input').check();
    assert.equal(await page.locator('.canvas-agent-run-settings input[type=number]').isVisible(),true);
    await page.screenshot({ path: path.join(out, 'permissions-1440.png') });
    checks.push('100 real browser opt-in toggles stay mounted without page errors');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.canvas-agent-run-settings').getAttribute('open'), null);
    checks.push('permission popover does not change composer height and Escape dismisses it');
    await page.getByRole('button', { name: '流式推理', exact: true }).click();
    assert.equal(await page.locator('.canvas-agent-turn').count(), 1);
    assert.equal(await page.locator('.canvas-agent-turn-process').getAttribute('open'), null);
    await page.locator('.canvas-agent-turn-process > summary').click();
    await page.locator('.canvas-agent-model-reasoning > summary').click();
    assert.equal(await page.locator('.canvas-agent-turn-process > summary > .canvas-agent-reasoning-preview').isVisible(),false);
    assert.equal(await page.locator('.canvas-agent-model-reasoning > summary > .canvas-agent-reasoning-preview').isVisible(),false);
    const beforeText = await page.locator('.canvas-agent-model-reasoning p').innerText();
    const wordmark = page.locator('.canvas-agent-live-wordmark');
    const beforeFlow = await wordmark.evaluate(el=>getComputedStyle(el).backgroundPosition);
    const disk = page.locator('.canvas-agent-turn-mark .canvas-agent-orb-black-hole').first();
    const firstFrame = await disk.screenshot();
    await page.waitForTimeout(1300);
    assert.ok((await page.locator('.canvas-agent-model-reasoning p').innerText()).length > beforeText.length,'fixture emits real incremental state updates');
    assert.notEqual(await wordmark.evaluate(el=>getComputedStyle(el).backgroundPosition),beforeFlow,'gradient progresses');
    assert.ok(!firstFrame.equals(await disk.screenshot()),'shared disk flow changes rendered pixels');
    checks.push('stream content grows, text light flows, and actual black hole pixels animate');
    assert.match(await page.locator('.canvas-agent-model-reasoning').innerText(), /正在思考.*秒/s);
    await page.screenshot({ path: path.join(out, 'reasoning-stream.png') });
    await page.getByRole('button',{name:'应用内减少动态',exact:true}).click();
    assert.equal(await page.locator('.canvas-agent-turn-mark .canvas-agent-orb-visual').getAttribute('data-motion'),'still');
    assert.equal(await wordmark.evaluate(el=>getComputedStyle(el).animationName),'none');
    const stillFrame = await disk.screenshot(); await page.waitForTimeout(400);
    assert.ok(stillFrame.equals(await disk.screenshot()),'application setting stops the actual disk, not only CSS');
    await page.getByRole('button',{name:'应用内减少动态',exact:true}).click();
    checks.push('application reduced-motion setting stops and restores shared renderer');
    await page.getByRole('button', { name: '直接回复', exact: true }).click();
    assert.equal(await page.locator('.canvas-agent-model-reasoning').count(), 0);
    checks.push('no fabricated reasoning block for text-only streaming');
    await page.getByRole('button', { name: '工具失败', exact: true }).click();
    await page.screenshot({ path: path.join(out, 'tool-failed.png') });
    await page.getByRole('button', { name: '完整对话', exact: true }).click();
    await page.getByRole('button', { name: '历史对话', exact: true }).click();
    const panel = await page.locator('.canvas-r1-agent-panel').boundingBox();
    const history = await page.locator('.canvas-agent-history-popover').boundingBox();
    assert.ok(history.x >= panel.x && history.x + history.width <= panel.x + panel.width + 1);
    await page.screenshot({ path: path.join(out, 'history-1440.png') });
    await page.getByRole('button', { name: '关闭历史对话', exact: true }).click();
    checks.push('history popover stays within panel');
    await page.setViewportSize({ width: 780, height: 540 });
    const compact = await page.locator('.canvas-r1-agent-composer').boundingBox();
    assert.ok(compact.y + compact.height <= 540);
    await page.screenshot({ path: path.join(out, 'conversation-780.png') });
    // Exercise repeated theme changes while real fixture streaming ticks rerender the panel.
    await page.getByRole('button',{name:'流式推理',exact:true}).click();
    const themeChecks=[];
    for(const width of [780,1440]){
      await page.setViewportSize({width,height:width===780?540:900});
      for(const theme of ['light','dark','light','dark']){
        await page.evaluate(async theme=>{document.documentElement.dataset.theme=theme;await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));},theme);
        const state=await page.evaluate(()=>Object.fromEntries(['html','.canvas-r1-agent-panel','.canvas-agent-user-bubble','.canvas-r1-agent-composer'].map(selector=>{const style=getComputedStyle(document.querySelector(selector));return [selector,{color:style.color,background:style.backgroundColor,surface:style.getPropertyValue('--theme-surface-panel').trim(),hover:style.getPropertyValue('--theme-hover').trim()}];})));
        themeChecks.push({width,theme,state});
        fs.writeFileSync(path.join(out,'theme-cycle-computed.json'),JSON.stringify(themeChecks,null,2));
        const foreground=theme==='light'?'rgb(24, 25, 31)':'rgb(240, 240, 242)';
        for(const selector of ['html','.canvas-r1-agent-panel','.canvas-agent-user-bubble','.canvas-r1-agent-composer']) assert.equal(state[selector].color,foreground,`${width} ${theme} ${selector} foreground`);
        assert.equal(state['.canvas-agent-user-bubble'].background,theme==='light'?'rgb(232, 234, 240)':'rgb(34, 34, 40)');
        assert.equal(state['.canvas-r1-agent-panel'].surface,theme==='light'?'#f0f1f4':'#111114');
        const sourceLength=await page.locator('.canvas-agent-model-reasoning p').last().textContent().then(text=>text.length);
        await page.waitForFunction(length=>{const el=document.querySelector('.canvas-agent-model-reasoning p');return el&&el.textContent.length>length;},sourceLength);
        assert.equal(await page.locator('.canvas-r1-agent-panel').evaluate(el=>getComputedStyle(el).color),foreground,'stream rerender preserves selected theme');
        await page.locator('.canvas-agent-run-settings > summary').click();
        assert.notEqual(await page.locator('.canvas-agent-run-settings').getAttribute('open'),null);
        assert.equal(await page.locator('.canvas-agent-run-settings > summary').evaluate(el=>getComputedStyle(el).color),foreground,'reopened menu preserves theme');
        await page.keyboard.press('Escape');
      }
    }
    fs.writeFileSync(path.join(out,'theme-cycle-computed.json'),JSON.stringify(themeChecks,null,2));
    await page.getByRole('button',{name:'完整对话',exact:true}).click();
    await page.setViewportSize({width:780,height:540});
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.evaluate(async () => { document.documentElement.dataset.theme = 'light'; await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))); });
    const themeState = await page.evaluate(() => {
      const colors = selector => { const el=document.querySelector(selector); const style=getComputedStyle(el); return {color:style.color,background:style.backgroundColor,surface:style.getPropertyValue('--theme-surface-panel').trim()}; };
      return {theme:document.documentElement.dataset.theme,root:colors('html'),panel:colors('.canvas-r1-agent-panel'),bubble:colors('.canvas-agent-user-bubble'),composer:colors('.canvas-r1-agent-composer')};
    });
    fs.writeFileSync(path.join(out,'light-theme-computed.json'),JSON.stringify(themeState,null,2));
    assert.equal(themeState.theme,'light');
    assert.equal(themeState.panel.surface,'#f0f1f4');
    assert.equal(themeState.panel.color,'rgb(24, 25, 31)');
    assert.equal(themeState.bubble.color,'rgb(24, 25, 31)');
    assert.equal(themeState.bubble.background,'rgb(232, 234, 240)');
    const luminance = rgb => {const c=rgb.map(value=>value/255).map(value=>value<=.04045?value/12.92:((value+.055)/1.055)**2.4);return c[0]*.2126+c[1]*.7152+c[2]*.0722;};
    const contrast=(luminance([232,234,240])+.05)/(luminance([24,25,31])+.05);
    assert.ok(contrast>=4.5,'light user text contrast meets normal-text minimum');
    await page.screenshot({ path: path.join(out, 'light-reduced-motion-780.png') });
    await page.setViewportSize({width:1440,height:900});
    await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
    await page.screenshot({ path: path.join(out, 'light-reduced-motion-1440.png') });
    checks.push('compact composer visible and committed light theme has readable text contrast');
    assert.deepEqual(errors, []);
    assert.deepEqual(unexpectedRequests, []);
    fs.writeFileSync(path.join(out, 'checks.json'), JSON.stringify({ checks, errors, fixture: 'synthetic-no-provider-calls' }, null, 2));
    console.log(`${checks.length} browser checks passed. ${out}`);
  } catch(error) {
    failure = String(error?.stack || error);
    if(page) await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});
    throw error;
  } finally {
    fs.writeFileSync(path.join(out,'checks.json'),JSON.stringify({checks,errors,unexpectedRequests,failure,fixture:'synthetic-no-provider-calls'},null,2));
    if(context) await context.tracing.stop({path:path.join(out,'trace.zip')}).catch(()=>{});
    await browser?.close(); await new Promise(resolve=>server.close(resolve)); esbuild.stop();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
