import {suppressPointerActivation} from './pointerActivation';
/** Direct controls use PointerEvents so native OS file drops stay enabled. */
export type ControlPointerStart = {
  button: number; pointerId: number; clientX: number; clientY: number; isPrimary?: boolean;
  currentTarget: EventTarget & HTMLElement;
};
let cancelCurrentControlDrag: (()=>void)|null=null;
export function beginControlPointerDrag(event: ControlPointerStart, onMove: (id: string, index: number) => void) {
  if (event.button !== 0 || event.isPrimary===false) return;
  cancelCurrentControlDrag?.();
  const source = event.currentTarget;
  const group = source.closest<HTMLElement>('[data-control-group]');
  const id = source.dataset.controlId;
  if (!group || !id) return;
  const axis = group.dataset.controlAxis === 'vertical' ? 'vertical' : 'horizontal';
  let dragging = false, insertion = -1;
  const clear = () => group.querySelectorAll<HTMLElement>('[data-control-id]').forEach(item => {
    delete item.dataset.controlDrop;
  });
  const cleanup = () => {
    clear(); source.classList.remove('control-dragging');
    window.removeEventListener('pointermove', move, true);
    window.removeEventListener('pointerup', up, true);
    window.removeEventListener('pointercancel', pointerCancel, true);
    window.removeEventListener('keydown', key, true);
    window.removeEventListener('blur', cancel);
    document.removeEventListener('visibilitychange',visibility);
    source.removeEventListener('lostpointercapture',cancel);
    if(source.hasPointerCapture?.(event.pointerId))source.releasePointerCapture(event.pointerId);
    if(cancelCurrentControlDrag===cancel)cancelCurrentControlDrag=null;
  };
  const finish = (commit: boolean, released = false) => {
    cleanup();
    if (dragging) {
      // The click generated by pointerup must not activate the moved command.
      suppressPointerActivation(source,event.pointerId,released);
      if (commit && insertion >= 0) onMove(id, insertion);
    }
  };
  const move = (pointer: PointerEvent) => {
    if (pointer.pointerId !== event.pointerId) return;
    if (!dragging && Math.hypot(pointer.clientX - event.clientX, pointer.clientY - event.clientY) < 7) return;
    if(!dragging)source.setPointerCapture?.(event.pointerId);
    dragging = true; pointer.preventDefault(); source.classList.add('control-dragging'); clear();
    const rect = group.getBoundingClientRect();
    if (pointer.clientX < rect.left - 24 || pointer.clientX > rect.right + 24 || pointer.clientY < rect.top - 24 || pointer.clientY > rect.bottom + 24) { insertion = -1; return; }
    const peers = Array.from(group.querySelectorAll<HTMLElement>('[data-control-id]')).filter(item => item !== source && item.getBoundingClientRect().width > 0).sort((a,b) => { const left=a.getBoundingClientRect(), right=b.getBoundingClientRect(); return axis==='vertical'?left.top-right.top:left.left-right.left; });
    const coordinate = axis === 'vertical' ? pointer.clientY : pointer.clientX;
    insertion = peers.findIndex(item => { const box = item.getBoundingClientRect(); return coordinate < (axis === 'vertical' ? box.top + box.height / 2 : box.left + box.width / 2); });
    if (insertion < 0) insertion = peers.length;
    const marker = peers[insertion] ?? peers[peers.length - 1];
    if (marker) marker.dataset.controlDrop = insertion === peers.length ? 'after' : 'before';
  };
  const up = (pointer: PointerEvent) => { if (pointer.pointerId === event.pointerId) { if(dragging)move(pointer); finish(true,true); } };
  const cancel = () => finish(false);
  const pointerCancel=(pointer:PointerEvent)=>{if(pointer.pointerId===event.pointerId)finish(false,true);};
  const visibility=()=>{if(document.hidden)cancel();};
  const key = (keyboard: KeyboardEvent) => { if (keyboard.key === 'Escape') { keyboard.preventDefault(); keyboard.stopPropagation(); cancel(); } };
  window.addEventListener('pointermove', move, { capture: true, passive: false });
  window.addEventListener('pointerup', up, true);
  window.addEventListener('pointercancel', pointerCancel, true);
  window.addEventListener('keydown', key, true);
  window.addEventListener('blur', cancel);
  document.addEventListener('visibilitychange',visibility);
  source.addEventListener('lostpointercapture',cancel);
  cancelCurrentControlDrag=cancel;
}
