export type MessageKey = keyof typeof zhCN;

export const messageCatalog: Record<Locale, Record<MessageKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export function isSupportedLocale(value: unknown): value is Locale {
  return typeof value === "string" && (SUPPORTED_LOCALES as readonly string[]).includes(value);
}

export function normalizeLocale(value: unknown): Locale {
  return isSupportedLocale(value) ? value : DEFAULT_LOCALE;
}

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  const template = messageCatalog[locale][key];
  return template.replace(/\{([a-zA-Z][\w]*)\}/g, (token, name: string) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : token
  ));
}

export function selectPluralKey<Key extends string>(locale: Locale, count: number, forms: PluralForms<Key>): Key {
  return locale === "en-US" && Math.abs(count) === 1 ? forms.one : forms.other;
}

export type I18nContextValue = {
  locale: Locale;
  t: (key: MessageKey, params?: MessageParams) => string;
  plural: (count: number, forms: PluralForms<MessageKey>, params?: MessageParams) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  const value = useMemo<I18nContextValue>(() => ({
    locale,
    t: (key, params) => translate(locale, key, params),
    plural: (count, forms, params) => translate(locale, selectPluralKey(locale, count, forms), { ...params, count }),
  }), [locale]);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  return createElement(I18nContext.Provider, { value }, children);
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within I18nProvider");
  return value;
}

export function useMessages<const Catalog extends ScopedMessageCatalog>(catalog: Catalog) {
  const { locale } = useI18n();
  return useMemo(() => ({
    locale,
    t<Key extends keyof Catalog & string>(key: Key, params: MessageParams = {}) {
      const template = catalog[key][locale];
      return template.replace(/\{([a-zA-Z][\w]*)\}/g, (token, name: string) => (
        Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : token
      ));
    },
    plural<Key extends keyof Catalog & string>(count: number, forms: PluralForms<Key>, params: MessageParams = {}) {
      const template = catalog[selectPluralKey(locale, count, forms)][locale];
      const values: MessageParams = { ...params, count };
      return template.replace(/\{([a-zA-Z][\w]*)\}/g, (token, name: string) => (
        Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token
      ));
    },
  }), [catalog, locale]);
}
