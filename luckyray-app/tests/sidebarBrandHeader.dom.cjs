const assert = require("node:assert/strict");
const { JSDOM } = require("jsdom");
const dom = new JSDOM('<div id="root"></div>', { url: "https://sidebar.qa.invalid" });
for (const key of ["window", "document", "HTMLElement", "Element", "Event", "MouseEvent", "CustomEvent", "localStorage", "navigator"])
  Object.defineProperty(global, key, { value: dom.window[key], configurable: true });
const React = require("react");
const { createRoot } = require("react-dom/client");
const { AppSidebar } = require(require("node:path").resolve(process.argv[2]));
const root = createRoot(document.getElementById("root"));
let checks = 0, manual = 0, compact = 0;
const eq = (a, b, message) => { assert.deepEqual(a, b, message); checks++; };
const tick = () => new Promise(resolve => setTimeout(resolve, 15));
const button = () => document.querySelector(".sidebar-brand-toggle");
const render = async (props = {}) => { root.render(React.createElement(AppSidebar, {
  route: "ai", onNavigate() {}, onManualToggle: () => manual++, onCompactToggle: () => compact++, ...props,
})); await tick(); };
const click = async () => { button().click(); await tick(); };
const collapsed = () => document.querySelector("aside").classList.contains("collapsed");
(async () => {
  await render();
  eq(collapsed(), false);
  eq(button().getAttribute("aria-label"), "收起");
  eq(button().getAttribute("aria-expanded"), "true");
  eq(button().getAttribute("type"), "button");
  eq(button().getAttribute("data-tauri-no-drag"), "true");
  eq(document.getElementById(button().getAttribute("aria-controls")).tagName, "NAV");
  eq(document.querySelectorAll(".sidebar-brand-toggle").length, 1);
  eq(document.querySelector(".sidebar-footer .sidebar-brand-toggle"), null);
  eq(document.querySelectorAll(".sidebar-footer .sidebar-toggle").length, 1, "Only layout management remains in footer");
  const stableButton = button(); stableButton.focus();
  await click();
  eq(collapsed(), true);
  eq(localStorage.getItem("luckyray-sidebar-collapsed-v1"), "1");
  eq(button(), stableButton, "Keyboard target must survive collapse");
  eq(document.activeElement, stableButton);
  eq(button().getAttribute("aria-label"), "展开");
  eq(button().getAttribute("aria-expanded"), "false");
  eq(document.querySelector(".sidebar-header").dataset.collapsed, "true");
  eq(button().querySelector("img").getAttribute("src"), "/luckyray-logo.png");
  button().dispatchEvent(new MouseEvent("mouseover", { bubbles: true })); await tick();
  eq(collapsed(), true, "Hover only reveals the icon, never opens the sidebar");
  eq(manual, 1);
  await click(); eq(collapsed(), false); eq(manual, 2);
  eq(localStorage.getItem("luckyray-sidebar-collapsed-v1"), "0");
  window.dispatchEvent(new Event("luckyray:shell-toggle-sidebar")); await tick(); eq(collapsed(), true);
  window.dispatchEvent(new CustomEvent("luckyray:folder-reveal", { detail: { scope: "materials" } })); await tick();
  eq(collapsed(), false, "Existing folder reveal still temporarily expands");
  await click(); eq(collapsed(), true, "Header closes temporary folder reveal without changing saved preference");
  eq(localStorage.getItem("luckyray-sidebar-collapsed-v1"), "1");
  await render({ compactAutoCollapsed: true, compactExpanded: false });
  await click(); eq(compact, 1); eq(collapsed(), true, "Compact state stays controlled by shell");
  await render({ compactAutoCollapsed: true, compactExpanded: true }); eq(collapsed(), false);
  await click(); eq(compact, 2);
  eq(localStorage.getItem("luckyray-sidebar-collapsed-v1"), "1", "Compact toggle must not overwrite desktop preference");
  await render({ applicationModalIsolated: true });
  eq(document.querySelector("aside").hasAttribute("inert"), true);
  eq(document.querySelector("aside").getAttribute("aria-hidden"), "true");
  await render({ key: "remount" }); eq(collapsed(), true, "Saved collapse restored on remount");
  await click(); eq(collapsed(), false);
  root.unmount();
  console.log(`Sidebar brand: ${checks} DOM assertions PASS; pixel/real keyboard activation requires browser QA`);
})().catch(error => { console.error(error); process.exitCode = 1; });
