// Production-component rendering with synthetic fixtures only. Optional Playwright tooling.
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const requireTool = process.env.LR_BROWSER_TOOLS ? createRequire(path.join(process.env.LR_BROWSER_TOOLS, 'package.json')) : require;
const { chromium } = requireTool('playwright');
const esbuild = require(require.resolve('esbuild', { paths: [fs.realpathSync(path.join(root, 'node_modules/vite'))] }));
const out = process.env.LR_AGENT_UI_OUT || path.join(root, 'output/canvas-agent-r6-ui');
const checks = [];
(async () => {
  fs.mkdirSync(out, { recursive: true });
  await esbuild.build({ entryPoints: [path.join(__dirname, 'canvasAgentR6Ui.fixture.tsx')], bundle: true, outfile: path.join(out, 'fixture.js'), loader: { '.css': 'css' } });
  const html = `<!doctype html><html data-theme="dark"><meta charset="UTF-8"><link rel="stylesheet" href="/fixture.css"><style>html,body,#root{margin:0;width:100%;height:100%;font-family:Arial,'Noto Sans CJK SC',sans-serif;background:#0b0c10;color:#e6e7eb}*{box-sizing:border-box}.fixture-stage{position:relative;width:100%;height:100%;background:radial-gradient(#343540 1px,transparent 1px) 0 0/22px 22px}.fixture-stage nav{position:absolute;left:20px;top:20px;display:flex;gap:10px}.fixture-stage nav button{padding:8px;background:#202127;border:1px solid #454650;border-radius:8px;color:#ddd}.fixture-art{position:absolute;left:12%;top:30%;font-size:24px;color:#b1b8c7}.fixture-art small{font-size:13px;color:#717989}.canvas-r1-agent-panel{top:76px;--canvas-panel-surface:#131419;--theme-surface-raised:#202127;--theme-border-strong:#383941;--theme-hover:rgba(255,255,255,.06);--text-primary:#e6e7eb}.canvas-agent-history-popover{background:var(--canvas-panel-surface)}</style><div id="root"></div><script src="/fixture.js"></script></html>`;
  const server = http.createServer((req, res) => { const name = req.url === '/' ? null : path.basename(req.url); if (!name) { res.setHeader('Content-Type','text/html'); res.end(html); } else if (['fixture.js','fixture.css'].includes(name)) { res.setHeader('Content-Type',name.endsWith('.js')?'text/javascript':'text/css'); res.end(fs.readFileSync(path.join(out,name))); } else { res.statusCode=404;res.end(); } });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.LR_CHROMIUM || '/usr/bin/chromium', args: ['--no-sandbox'] });
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.address().port}/`);
    await page.locator('.canvas-agent-turn').waitFor();
    const historicalMark = page.locator('.canvas-agent-turn-mark .canvas-agent-orb-fallback').first();
    assert.deepEqual(await historicalMark.evaluate(el => ({width:getComputedStyle(el).width,height:getComputedStyle(el).height})), {width:'88px',height:'64px'});
    assert.ok((await historicalMark.boundingBox()).width > 30, 'historical mark must not inherit the old 14px generic SVG rule');
    checks.push('historical static black hole keeps its scoped dimensions');
    await page.mouse.move(10, 890);
    const actions = page.locator('.canvas-agent-turn .canvas-agent-message-actions').last();
    assert.equal(await actions.evaluate(el => getComputedStyle(el).opacity), '0');
    await page.locator('.canvas-agent-turn').hover();
    await page.waitForTimeout(200);
    assert.equal(await actions.evaluate(el => getComputedStyle(el).opacity), '1');
    assert.equal(await actions.locator('button').allTextContents().then(values => values.every(value => !value)), true);
    checks.push('assistant icon actions are hidden at rest and revealed on hover');
    assert.equal(await page.locator('.canvas-agent-user-bubble .canvas-agent-message-actions').count(), 0);
    checks.push('user actions are outside message bubble');
    await page.mouse.move(10, 890);
    await page.screenshot({ path: path.join(out, 'conversation-1440.png') });
    await page.getByRole('button', { name: '旧版九段', exact: true }).click();
    assert.equal(await page.locator('.canvas-agent-turn').count(), 1);
    await page.screenshot({ path: path.join(out, 'legacy-nine-fragments.png') });
    checks.push('legacy nine assistant fragments render as one turn');
    await page.getByRole('button', { name: '完整对话', exact: true }).click();
    const composerBefore = await page.locator('.canvas-r1-agent-composer').boundingBox();
    await page.locator('.canvas-agent-run-settings > summary').click();
    const composerAfter = await page.locator('.canvas-r1-agent-composer').boundingBox();
    assert.ok(Math.abs(composerBefore.height - composerAfter.height) < 1);
    await page.screenshot({ path: path.join(out, 'permissions-1440.png') });
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.canvas-agent-run-settings').getAttribute('open'), null);
    checks.push('permission popover does not change composer height and Escape dismisses it');
    await page.getByRole('button', { name: '流式推理', exact: true }).click();
    assert.equal(await page.locator('.canvas-agent-turn').count(), 1);
    assert.equal(await page.locator('.canvas-agent-turn-process').getAttribute('open'), '');
    await page.screenshot({ path: path.join(out, 'reasoning-stream.png') });
    await page.getByRole('button', { name: '直接回复', exact: true }).click();
    assert.equal(await page.locator('.canvas-agent-model-reasoning').count(), 0);
    checks.push('no fabricated reasoning block for text-only streaming');
    await page.getByRole('button', { name: '工具失败', exact: true }).click();
    await page.screenshot({ path: path.join(out, 'tool-failed.png') });
    await page.getByRole('button', { name: '完整对话', exact: true }).click();
    await page.getByRole('button', { name: '历史对话', exact: true }).click();
    const panel = await page.locator('.canvas-r1-agent-panel').boundingBox();
    const history = await page.locator('.canvas-agent-history-popover').boundingBox();
    assert.ok(history.x >= panel.x && history.x + history.width <= panel.x + panel.width + 1);
    await page.screenshot({ path: path.join(out, 'history-1440.png') });
    await page.getByRole('button', { name: '关闭历史对话', exact: true }).click();
    checks.push('history popover stays within panel');
    await page.setViewportSize({ width: 780, height: 540 });
    const compact = await page.locator('.canvas-r1-agent-composer').boundingBox();
    assert.ok(compact.y + compact.height <= 540);
    await page.screenshot({ path: path.join(out, 'conversation-780.png') });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
    await page.screenshot({ path: path.join(out, 'light-reduced-motion-780.png') });
    checks.push('compact viewport keeps composer visible; light/reduced-motion captured');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(out, 'checks.json'), JSON.stringify({ checks, errors, fixture: 'synthetic-no-provider-calls' }, null, 2));
    console.log(`${checks.length} browser checks passed. ${out}`);
  } finally { await browser?.close(); await new Promise(resolve=>server.close(resolve)); esbuild.stop(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
