const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<div id="root"></div>', { url: 'https://qa.invalid' });
for (const key of ['window', 'document', 'HTMLElement', 'Element', 'Node', 'Event', 'MouseEvent', 'navigator']) Object.defineProperty(global, key, { value: dom.window[key], configurable: true });
const React = require('react'), { createRoot } = require('react-dom/client');
const { CanvasCinematography, createDefaultCinematographySettings } = require(require('node:path').resolve(process.argv[2]));
const wait = () => new Promise(resolve => setTimeout(resolve, 25));
(async () => {
  const root = createRoot(document.getElementById('root'));
  let value = createDefaultCinematographySettings(), changes = 0, kind = 'image', english = true;
  const render = async () => { root.render(React.createElement(CanvasCinematography, { value, kind, english, onChange: next => { value = next; changes++; void render(); } })); await wait(); };
  const button = text => [...document.querySelectorAll('button')].find(node => node.textContent.trim() === text);
  await render();
  assert.equal(document.querySelector('input').checked, false);
  assert.equal(document.querySelector('fieldset').disabled, true);
  assert.equal(document.querySelectorAll('select').length, 4);
  assert.equal(document.querySelectorAll('.is-focalLength button').length, 8);
  button('35').click(); await wait(); assert.equal(changes, 0);
  document.querySelector('input').click(); await wait(); assert.equal(value.enabled, true);
  button('35').click(); await wait(); assert.equal(value.focalLength, '35'); assert.equal(button('35').getAttribute('aria-pressed'), 'true');
  button('f/1.4').click(); await wait(); assert.equal(value.aperture, '1.4');
  const camera = document.querySelector('select'); camera.value = 'imax'; camera.dispatchEvent(new Event('change', { bubbles: true })); await wait(); assert.equal(value.camera, 'imax');
  kind = 'video'; await render(); assert.equal(document.querySelectorAll('select').length, 5);
  const movement = document.querySelector('.canvas-cinema-motion select'); movement.value = 'orbit'; movement.dispatchEvent(new Event('change', { bubbles: true })); await wait(); assert.equal(value.movement, 'orbit');
  kind = 'image'; await render(); assert.equal(document.querySelector('.canvas-cinema-motion'), null); assert.equal(value.movement, 'orbit');
  button('Reset').click(); await wait(); assert.deepEqual(value, createDefaultCinematographySettings());
  english = false; await render(); assert.match(document.querySelector('section').textContent, /摄影指导/);
  kind = 'text'; await render(); assert.equal(document.querySelector('input').disabled, true); assert.equal(document.querySelector('fieldset'), null);
  root.unmount(); console.log('Cinematography DOM: default disabled, immediate controlled selection, camera, segmented optics, video-only movement, reset and localization passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
